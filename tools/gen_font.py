def main(out):
    rows = []
    for c in range(32, 96):
        ch = chr(c)
        art = G.get(ch, G['?'])
        rr = art.split('|')
        assert len(rr) == 7 and all(len(r) == 5 for r in rr), ch
        rows.append([sum(1 << (4 - i) for i, p in enumerate(r) if p == '#') for r in rr])
    L = ["/* generated by tools/gen_font.py: FM1 Tape OS's 5x7 font (original artwork) */",
         "static const uint8_t FONT5X7[64][7] = {"]
    for c, r in zip(range(32, 96), rows):
        L.append("    {" + ", ".join(f"0x{b:02x}" for b in r) + "},  /* " + repr(chr(c)) + " */")
    L.append("};")
    open(out, "w").write("\n".join(L) + "\n")


if __name__ == "__main__":
    main(sys.argv[1])
